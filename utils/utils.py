async def calculate_date(days: int):
    """Получение даты последней меснтруации / рождения малыша"""
    logging.info('calculate_date')
    today = datetime.date.today() - timedelta(days=days)
    finish_date = today.strftime('%d.%m.%Y')
    return finish_date


